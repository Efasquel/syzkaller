#!/bin/sh
# culprit2c.sh -- turn a bug's minimized culprit into a standalone C reproducer
# with a Makefile, in the bug registry, for a vendor report (Apple will not run
# syzkaller).
#
#   scripts/culprit2c.sh BUG-NNNN [triage job name | path to a .syz]
#
# By default the culprit is the one the registry records for the bug
# (registry.json -> reproducer.path). Pass a triage job (or a .syz file) to use
# another of the bug's reproducers instead.
#
# Writes, in <bugs dir>/BUG-NNNN/repro/:
#   <name>.syz   the culprit, as minimized
#   <name>.c     the generated reproducer
#   Makefile     builds every .c here (`make`), needs only Xcode's clang
# and builds it once to check that it compiles. Nothing is executed: running
# the binary is up to you (it is expected to crash the machine).
#
# Requirements:
#   - syz-prog2c built from a tree whose descriptions match the run that found
#     the culprit (`make prog2c`, or set SYZ_PROG2C). A tree without the run's
#     syscalls fails with "unknown syscall ...".
#   - GNU cpp: pkg/csource preprocesses with -fdirectives-only, which clang does
#     not support. `brew install gcc`; any g++-N on PATH is picked up, or set
#     SYZ_CPP. Optional: clang-format, to indent the generated source.
set -eu

die() { echo "culprit2c: $*" >&2; exit 1; }

[ $# -ge 1 ] || die "usage: $0 BUG-NNNN [triage job | file.syz]"
repo=$(cd "$(dirname "$0")/.." && pwd)
bug="$1"
bugs="${SYZ_BUGS_DIR:-/Users/Shared/fuzz-run/campaigns/bugs}"
triage="${SYZ_TRIAGE_DIR:-/Users/Shared/fuzz-run/triage}"
[ -f "$bugs/registry.json" ] || die "no registry at $bugs/registry.json"

if [ $# -ge 2 ]; then
  case "$2" in
    *.syz) prog="$2" ;;
    */*)   prog="$2/final_culprit.syz" ;;
    *)     prog="$triage/$2/final_culprit.syz" ;;
  esac
else
  prog=$(/usr/bin/python3 - "$bugs/registry.json" "$bug" <<'PY'
import json, sys
for b in json.load(open(sys.argv[1]))["bugs"].values():
    if b.get("id") == sys.argv[2]:
        print((b.get("reproducer") or {}).get("path", ""))
        break
PY
)
  [ -n "$prog" ] || die "$bug has no reproducer in the registry; pass a triage job"
fi
[ -f "$prog" ] || die "no culprit program at $prog"

# Name the files after the triage job that minimized the culprit.
name=$(basename "$(dirname "$prog")")
[ "$(basename "$prog")" = final_culprit.syz ] || name=$(basename "$prog" .syz)

prog2c="${SYZ_PROG2C:-$repo/bin/syz-prog2c}"
[ -x "$prog2c" ] || die "no syz-prog2c at $prog2c (run: make prog2c, or set SYZ_PROG2C)"

out="$bugs/$bug/repro"
mkdir -p "$out"
cp "$prog" "$out/$name.syz"

# Threaded mode honours (async) call properties, which minimized culprits keep.
# sandbox none matches how the campaigns run the executor.
log="$out/$name.prog2c.log"
"$prog2c" -prog "$prog" -os darwin -arch arm64 -sandbox none -threaded \
  -repeat 1 -procs 1 > "$out/$name.c.tmp" 2> "$log" ||
  { rm -f "$out/$name.c.tmp"; die "syz-prog2c failed: $(head -3 "$log")"; }
mv "$out/$name.c.tmp" "$out/$name.c"
grep -q "clang-format" "$log" &&
  echo "note: clang-format not found, $name.c is not indented (brew install clang-format)"
[ -s "$log" ] || rm -f "$log"

cat > "$out/Makefile" <<'MK'
# Standalone reproducers for this bug, generated by syzkaller's syz-prog2c from
# the minimized culprit (<name>.syz next to each <name>.c).
#   make          build every reproducer
#   ./<name>      run one -- expected to panic the machine
# Needs only Xcode's command line tools (clang, IOKit headers).
CC      = clang
CFLAGS  ?= -O1 -Wno-deprecated-declarations
LDLIBS  += -framework IOKit -framework CoreFoundation
PROGS   := $(patsubst %.c,%,$(wildcard *.c))

all: $(PROGS)

%: %.c
	$(CC) $(CFLAGS) -o $@ $< $(LDLIBS)

clean:
	rm -f $(PROGS)

.PHONY: all clean
MK

make -s -C "$out" "$name" > "$out/$name.build.log" 2>&1 ||
  die "compile failed, see $out/$name.build.log"
[ -s "$out/$name.build.log" ] || rm -f "$out/$name.build.log"

echo "bug     : $bug"
echo "culprit : $prog"
echo "written : $out/{$name.syz,$name.c,Makefile}"
echo "built   : $out/$name"
echo "run it as a standard user, on a machine you can afford to crash:"
echo "  $out/$name"
